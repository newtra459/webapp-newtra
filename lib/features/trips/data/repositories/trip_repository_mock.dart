    return _all.where((t) => t.type == filter).toList();
  }

  @override
  Future<TripModel> getTripDetail(String tripId) async {
    await Future.delayed(const Duration(milliseconds: 300));
    return _all.firstWhere(
      (t) => t.id == tripId,
      orElse: () => _all.first,
    );
  }
